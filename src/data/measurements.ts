function build24hTrend(basePm25: number, basePm10: number, baseAqi: number, coastalMod: boolean): TrendPoint[] {
  const hours = [
    '00:00', '02:00', '04:00', '06:00', '08:00', '10:00',
    '12:00', '14:00', '16:00', '18:00', '20:00', '22:00',
  ];
  const diurnalFactors = coastalMod
    ? [0.92, 0.88, 0.86, 0.96, 1.14, 1.04, 0.82, 0.74, 0.80, 1.05, 1.12, 1.0]
    : [1.08, 1.04, 1.02, 1.10, 1.24, 1.12, 0.88, 0.78, 0.86, 1.16, 1.26, 1.14];

  return hours.map((time, idx) => {
    const f = diurnalFactors[idx];
    return {
      time,
      hourOffset: idx * 2 - 22,
      pm25: Math.round(basePm25 * f),
      pm10: Math.round(basePm10 * (0.95 + (f - 0.95) * 0.85)),
      aqi: Math.round(baseAqi * f),
    };
  });
}

function build7dTrend(basePm25: number, basePm10: number, baseAqi: number): TrendPoint[] {
  const days = ['Thu', 'Fri', 'Sat', 'Sun', 'Mon', 'Tue', 'Today'];
  const factors = [1.06, 1.12, 0.94, 0.86, 1.08, 1.03, 1.0];
  return days.map((time, idx) => {
    const f = factors[idx];
    return {
      time,
      hourOffset: idx - 6,
      pm25: Math.round(basePm25 * f),
      pm10: Math.round(basePm10 * f),
      aqi: Math.round(baseAqi * f),
    };
  });
}

